"""
Geometry comparison tests: DSL-generated meshes vs reference STLs.

These tests validate that the yapCAD DSL output matches the original
PhoneBot STL files within a Hausdorff-distance tolerance.

Reference STLs must be placed in reference/stl/ (downloaded from phonebot.dev).
Tests are skipped if the reference STLs are not present.
"""

import os
import pathlib
import numpy as np
import pytest

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
STL_DIR = REPO_ROOT / "reference" / "stl"


def _stl_available(name: str) -> bool:
    """Check if a reference STL file exists."""
    return (STL_DIR / name).exists()


def _load_stl_vertices(path: pathlib.Path) -> np.ndarray:
    """
    Load STL and return vertex array.

    Uses numpy-stl if available, falls back to trimesh.
    """
    try:
        import stl
        mesh = stl.mesh.Mesh.from_file(str(path))
        return mesh.vectors.reshape(-1, 3)
    except ImportError:
        import trimesh
        mesh = trimesh.load(str(path))
        return np.array(mesh.vertices)


def _load_dsl_mesh(part_name: str) -> np.ndarray:
    """
    Load a mesh generated by the DSL from the build output.

    This requires the yapCAD build to have been run first.
    """
    build_dir = REPO_ROOT / "build" / "stl"
    path = build_dir / f"{part_name}.stl"
    if not path.exists():
        pytest.skip(f"DSL-generated STL not found: {path}")
    return _load_stl_vertices(path)


def _hausdorff_distance_sampled(
    vertices_a: np.ndarray,
    vertices_b: np.ndarray,
    n_samples: int = 1000,
) -> float:
    """
    Approximate Hausdorff distance by sampling nearest neighbors.

    Returns the maximum of:
      max(min(dist(a_i, B))) and max(min(dist(b_j, A)))
    """
    from scipy.spatial import cKDTree

    # Sample subset if too many vertices
    if len(vertices_a) > n_samples:
        idx = np.random.choice(len(vertices_a), n_samples, replace=False)
        a_sample = vertices_a[idx]
    else:
        a_sample = vertices_a

    if len(vertices_b) > n_samples:
        idx = np.random.choice(len(vertices_b), n_samples, replace=False)
        b_sample = vertices_b[idx]
    else:
        b_sample = vertices_b

    tree_a = cKDTree(a_sample)
    tree_b = cKDTree(b_sample)

    # dist from B → nearest in A
    dists_ba, _ = tree_a.query(b_sample)
    # dist from A → nearest in B
    dists_ab, _ = tree_b.query(a_sample)

    return float(max(dists_ba.max(), dists_ab.max()))


@pytest.mark.requires_occ
@pytest.mark.expensive_geometry
@pytest.mark.parametrize("part_name", [
    pytest.param("thigh_link", marks=pytest.mark.skipif(
        not _stl_available("thigh_link.stl"),
        reason="reference STL not present"
    )),
    pytest.param("shin_link", marks=pytest.mark.skipif(
        not _stl_available("shin_link.stl"),
        reason="reference STL not present"
    )),
    pytest.param("foot_plate", marks=pytest.mark.skipif(
        not _stl_available("foot_plate.stl"),
        reason="reference STL not present"
    )),
])
def test_dsl_geometry_matches_stl(part_name: str):
    """
    Validate that the DSL-generated mesh for a part matches the
    reference STL within 2 mm Hausdorff distance.
    """
    ref_path = STL_DIR / f"{part_name}.stl"
    if not ref_path.exists():
        pytest.skip(f"Reference STL not found: {ref_path}")

    ref_vertices = _load_stl_vertices(ref_path)
    dsl_vertices = _load_dsl_mesh(part_name)

    hd = _hausdorff_distance_sampled(ref_vertices, dsl_vertices)

    # 2 mm tolerance for pre-alpha geometry
    assert hd < 2.0, (
        f"Hausdorff distance for {part_name}: {hd:.2f} mm "
        f"(tolerance: 2.0 mm)"
    )


def test_reference_stl_dir_exists():
    """Check that the reference STL directory is present."""
    assert STL_DIR.exists(), (
        f"reference/stl/ directory not found. "
        f"Download STL files from phonebot.dev and place in {STL_DIR}"
    )


def test_reference_stl_files_present():
    """List which reference STLs are available vs missing."""
    if not STL_DIR.exists():
        pytest.skip("reference/stl/ directory not found")

    stl_files = list(STL_DIR.glob("*.stl"))
    assert len(stl_files) > 0, (
        f"No STL files found in {STL_DIR}. "
        f"Download from phonebot.dev."
    )


